def dfs(start, goal):
  to_do = [start]
  visited = []
  order = []

  while to_do:
    room = to_do.pop()

    if room in visited:
      continue
    visited.append(room)
    order.append(room)

    if room == goal:
      return order

    for nxt in map_rooms[room]:
        to_do.append(nxt)

  return order

