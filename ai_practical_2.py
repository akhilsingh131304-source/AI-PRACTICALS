door_cost = {
    "A": {"B": 1, "C": 1},
    "B": {"D": 1},
    "C": {"D": 1},
    "D": {"G": 1},
    "G": {}
}

def path_cost(path):
  total = 0
  for i in range(len(path) - 1):
    current_room = path[i]
    next_room = path[i + 1]
    if current_room in door_cost and next_room in door_cost[current_room]:
      total += door_cost[current_room][next_room]
    else:

      return -1
  return total


