def evaluate_specific_path(path, graph):
    if not path or len(path) < 2:
        return False, 0, "Path is too short or empty."

    current_cost = 0
    for i in range(len(path) - 1):
        current_room = path[i]
        next_room = path[i+1]
        if next_room in graph.get(current_room, []):
            current_cost += 1
        else:
            return False, current_cost, f"Invalid transition from {current_room} to {next_room}."
    return True, current_cost, "Valid path."

